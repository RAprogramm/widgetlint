/// Whether `property` is a recognized standard CSS property name.
///
/// Vendor-prefixed names (starting with `-`) and custom properties (starting
/// with `--`) are treated as known: they are outside the scope of TGW216.
///
/// # Examples
///
/// ```
/// assert!(wl_css::known_properties::is_known("float"));
/// assert!(wl_css::known_properties::is_known("content"));
/// assert!(!wl_css::known_properties::is_known("colr"));
/// ```
#[must_use]
pub fn is_known(property: &str) -> bool {
    property.starts_with('-') || KNOWN_PROPERTIES.binary_search(&property).is_ok()
}
